import AppKit
import CryptoKit
import QuickLookThumbnailing
import QuickbarCore

/// Watches the pasteboard on a background queue and keeps the history.
/// Everything here that touches the pasteboard or the disk runs on `queue`.
final class ClipboardStore {
    static let shared = ClipboardStore()

    private let queue = DispatchQueue(label: "quickbar.clipboard", qos: .utility)
    private var history = ClipboardHistory()
    private var lastChangeCount = -1
    private var timer: DispatchSourceTimer?
    private var persist = true
    private let saver = Debouncer(delay: 1.0, queue: DispatchQueue(label: "quickbar.clipboard.save", qos: .utility))

    /// Main-thread copy, so the panel can show without waiting.
    private(set) var entries: [ClipboardEntry] = []

    /// Marker types password managers set on secrets and one-time values.
    private static let skippedTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]

    /// Rich forms of copied text kept next to the plain text, so pasting an
    /// old entry keeps its formatting.
    private static let richTypes: [(type: NSPasteboard.PasteboardType, ext: String)] = [(.rtf, "rtf"), (.html, "html")]

    /// Images, RTF and HTML are stored as files here, named by the history.
    static let dataFolder = AppPaths.support.appendingPathComponent("clipboard-data", isDirectory: true)
    /// One copied thing larger than this is not kept.
    static let maxEntryDataBytes = 32 * 1024 * 1024
    /// Oldest stored data is dropped beyond this total.
    static let dataBudgetBytes = 512 * 1024 * 1024

    func start(config: Config) {
        queue.async {
            self.persist = config.clipboardPersist
            if config.clipboardPersist, let data = try? Data(contentsOf: AppPaths.clipboard),
               let saved = try? JSONDecoder().decode(ClipboardHistory.self, from: data) {
                self.history = saved
            }
            self.history.maxEntries = config.clipboardMaxEntries
            self.reconcileData()
            self.publish(save: false)

            let timer = DispatchSource.makeTimerSource(queue: self.queue)
            timer.schedule(deadline: .now(), repeating: .milliseconds(300), leeway: .milliseconds(100))
            timer.setEventHandler { [weak self] in self?.poll() }
            timer.resume()
            self.timer = timer
        }
    }

    func apply(config: Config) {
        queue.async {
            self.persist = config.clipboardPersist
            self.history.maxEntries = config.clipboardMaxEntries
            if !config.clipboardPersist { try? FileManager.default.removeItem(at: AppPaths.clipboard) }
        }
    }

    // MARK: Stored data

    /// Makes the data folder and the history agree: entries whose files are
    /// gone are dropped, files no entry names are deleted.
    private func reconcileData() {
        let fm = FileManager.default
        try? fm.createDirectory(at: Self.dataFolder, withIntermediateDirectories: true,
                                attributes: [.posixPermissions: 0o700])
        let present = Set((try? fm.contentsOfDirectory(atPath: Self.dataFolder.path)) ?? [])
        history.removeAll { entry in entry.payloads.contains { !present.contains($0.file) } }
        let named = Set(history.entries.flatMap { $0.payloads.map(\.file) })
        for file in present.subtracting(named) {
            try? fm.removeItem(at: Self.dataFolder.appendingPathComponent(file))
        }
    }

    private func deleteData(of dropped: [ClipboardEntry]) {
        for payload in dropped.flatMap(\.payloads) {
            try? FileManager.default.removeItem(at: Self.dataFolder.appendingPathComponent(payload.file))
        }
    }

    private func store(_ blobs: [(type: NSPasteboard.PasteboardType, ext: String, data: Data)], id: String) -> [ClipboardEntry.Payload]? {
        var payloads = [ClipboardEntry.Payload]()
        for (i, blob) in blobs.enumerated() {
            let name = "\(id)-\(i).\(blob.ext)"
            let url = Self.dataFolder.appendingPathComponent(name)
            do {
                try blob.data.write(to: url, options: .atomic)
                try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            } catch {
                Log.info("clipboard: could not store \(blob.ext) data: \(error)")
                deleteData(of: [ClipboardEntry(kind: .image, payloads: payloads)])
                return nil
            }
            payloads.append(.init(type: blob.type.rawValue, file: name, bytes: blob.data.count))
        }
        return payloads
    }

    // MARK: Capture

    private func poll() {
        let pasteboard = NSPasteboard.general
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        let types = pasteboard.types ?? []
        guard !types.contains(where: { Self.skippedTypes.contains($0.rawValue) }) else { return }

        // Files copied in Finder: remember where they are, not their contents.
        if types.contains(.fileURL),
           let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            let paths = urls.map(\.path)
            record(ClipboardEntry(kind: .files, text: paths.joined(separator: "\n"), files: paths), blobs: [])
            return
        }

        let string = pasteboard.string(forType: .string)
        // Office apps put a picture of the text next to the text, so an image
        // only counts as the content when there is no rich text and at most a
        // bare word or URL beside it (browsers add the image's address).
        let stringIsIncidental = string.map { !$0.contains(where: \.isWhitespace) || !ClipboardHistory.isKeepable($0) } ?? true
        if !types.contains(.rtf), stringIsIncidental, let png = Self.pngData(from: pasteboard),
           png.count <= Self.maxEntryDataBytes, let rep = NSBitmapImageRep(data: png) {
            let entry = ClipboardEntry(kind: .image, text: string ?? "", width: rep.pixelsWide, height: rep.pixelsHigh,
                                       hash: Self.digest(png))
            record(entry, blobs: [(.png, "png", png)])
            return
        }

        guard let string, ClipboardHistory.isKeepable(string) else { return }
        var blobs = [(type: NSPasteboard.PasteboardType, ext: String, data: Data)]()
        for rich in Self.richTypes where types.contains(rich.type) {
            if let data = pasteboard.data(forType: rich.type), data.count <= Self.maxEntryDataBytes / 8 {
                blobs.append((rich.type, rich.ext, data))
            }
        }
        record(ClipboardEntry(text: string), blobs: blobs)
    }

    /// PNG if the app offered one, otherwise its TIFF converted (TIFF is
    /// uncompressed and several times larger on disk).
    private static func pngData(from pasteboard: NSPasteboard) -> Data? {
        if let png = pasteboard.data(forType: .png) { return png }
        guard let tiff = pasteboard.data(forType: .tiff), tiff.count <= 8 * maxEntryDataBytes,
              let rep = NSBitmapImageRep(data: tiff)
        else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    private static func digest(_ data: Data) -> String {
        SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
    }

    /// Adds `entry` unless the same thing is already there, in which case
    /// that one moves to the front and nothing new is written.
    private func record(_ entry: ClipboardEntry, blobs: [(type: NSPasteboard.PasteboardType, ext: String, data: Data)]) {
        switch history.promote(key: entry.key, date: entry.date) {
        case .alreadyFirst: return
        case .moved: publish(save: true); return
        case .absent: break
        }
        var entry = entry
        if !blobs.isEmpty {
            if let payloads = store(blobs, id: entry.id) {
                entry.payloads = payloads
            } else if entry.kind == .image {
                return
            }
        }
        var dropped = history.insert(entry)
        dropped += history.trimPayloads(toBytes: Self.dataBudgetBytes)
        deleteData(of: dropped)
        publish(save: true)
    }

    private func publish(save: Bool) {
        let snapshot = history
        DispatchQueue.main.async { self.entries = snapshot.entries }
        if save, persist {
            saver.call {
                let data = (try? JSONEncoder().encode(snapshot)) ?? Data()
                Disk.write(data, to: AppPaths.clipboard, privateFile: true)
            }
        }
    }

    // MARK: Using entries

    /// Puts `entry` back on the pasteboard, in every form it was stored in,
    /// and moves it to the front of the history.
    func activate(_ entry: ClipboardEntry) {
        queue.async {
            let pasteboard = NSPasteboard.general
            pasteboard.clearContents()
            switch entry.kind {
            case .files:
                pasteboard.writeObjects(entry.files.map { URL(fileURLWithPath: $0) as NSURL })
            case .text, .image:
                if !entry.text.isEmpty { pasteboard.setString(entry.text, forType: .string) }
                for payload in entry.payloads {
                    guard let data = try? Data(contentsOf: Self.dataFolder.appendingPathComponent(payload.file)) else { continue }
                    pasteboard.setData(data, forType: NSPasteboard.PasteboardType(payload.type))
                    // Some older apps only take TIFF.
                    if payload.type == NSPasteboard.PasteboardType.png.rawValue,
                       let tiff = NSBitmapImageRep(data: data)?.tiffRepresentation {
                        pasteboard.setData(tiff, forType: .tiff)
                    }
                }
            }
            self.lastChangeCount = pasteboard.changeCount
            if self.history.promote(key: entry.key) == .moved { self.publish(save: true) }
        }
    }

    func remove(_ entry: ClipboardEntry) {
        queue.async {
            if let i = self.history.entries.firstIndex(where: { $0.id == entry.id }),
               let removed = self.history.remove(at: i) {
                self.deleteData(of: [removed])
                self.publish(save: true)
            }
        }
    }

    func clear() {
        queue.async {
            self.deleteData(of: self.history.clear())
            self.publish(save: true)
        }
    }

    /// Hands any waiting save to the disk queue. Blocks briefly; only for quitting.
    func flush() {
        queue.sync { saver.flush() }
    }

    // MARK: Thumbnails

    private let thumbnailQueue = DispatchQueue(label: "quickbar.clipboard.thumbnails", qos: .userInitiated)
    private let thumbnails = NSCache<NSString, NSImage>()

    /// A small picture of an image entry or of a copied file, made off the
    /// main thread. `completion` runs on the main thread; nil if there is none.
    func thumbnail(for entry: ClipboardEntry, maxPixels: CGFloat, completion: @escaping (NSImage?) -> Void) {
        if let cached = thumbnails.object(forKey: entry.id as NSString) {
            completion(cached)
            return
        }
        let finish: (NSImage?) -> Void = { [thumbnails] image in
            if let image { thumbnails.setObject(image, forKey: entry.id as NSString) }
            DispatchQueue.main.async { completion(image) }
        }
        switch entry.kind {
        case .text:
            completion(nil)
        case .image:
            guard let file = entry.payloads.first(where: { $0.type == NSPasteboard.PasteboardType.png.rawValue })?.file else {
                completion(nil)
                return
            }
            thumbnailQueue.async {
                let url = Self.dataFolder.appendingPathComponent(file) as CFURL
                let options: [CFString: Any] = [
                    kCGImageSourceCreateThumbnailFromImageAlways: true,
                    kCGImageSourceCreateThumbnailWithTransform: true,
                    kCGImageSourceThumbnailMaxPixelSize: maxPixels,
                ]
                guard let source = CGImageSourceCreateWithURL(url, nil),
                      let image = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary)
                else { return finish(nil) }
                finish(NSImage(cgImage: image, size: .zero))
            }
        case .files:
            // Quick Look draws a preview for whatever the file is: images, video, PDFs, audio.
            guard let path = entry.files.first else {
                completion(nil)
                return
            }
            let request = QLThumbnailGenerator.Request(
                fileAt: URL(fileURLWithPath: path), size: CGSize(width: maxPixels, height: maxPixels),
                scale: 1, representationTypes: .all)
            QLThumbnailGenerator.shared.generateBestRepresentation(for: request) { representation, _ in
                finish(representation?.nsImage)
            }
        }
    }
}

/// The cmd-\ panel. Each press of the hotkey moves down one entry; releasing
/// the modifier puts the selected entry on the clipboard.
final class ClipboardPanelController: NSObject, NSTableViewDataSource, NSTableViewDelegate, NSWindowDelegate {
    static let width: CGFloat = 560
    static let rowHeight: CGFloat = 30
    static let maxVisibleRows = 12
    static let previewHeight: CGFloat = 132
    static let headerHeight: CGFloat = 34

    private let panel = FloatingPanel(size: NSSize(width: ClipboardPanelController.width, height: 200))
    private let table: ResultsTableView
    private let scroll: NSScrollView
    private let preview = NSTextField(wrappingLabelWithString: "")
    private let previewImage = NSImageView()
    /// Which entry the preview area is showing, so a late thumbnail for an
    /// entry the selection has left is ignored.
    private var previewedID = ""
    private var previewLeading: NSLayoutConstraint!
    private let separator = NSBox()
    private let headerSeparator = NSBox()
    private let footerSeparator = NSBox()
    private let header = NSTextField(labelWithString: "Clipboard History")
    private let counter = NSTextField(labelWithString: "")
    private let hints = KeyHintBar()
    private var entries: [ClipboardEntry] = []
    private var modifierTimer: Timer?
    private var heldModifiers: NSEvent.ModifierFlags = []
    private var sawModifiersHeld = false
    private var shownAt = Date.distantPast
    /// Fixed while the panel is open so ages don't change under the cursor.
    private var now = Date()

    override init() {
        (table, scroll) = NSTableView.makeResultsTable(rowHeight: Self.rowHeight)
        super.init()
        guard let content = panel.contentView else { return }
        panel.delegate = self
        table.dataSource = self
        table.delegate = self
        table.target = self
        table.doubleAction = #selector(rowDoubleClicked)

        for box in [separator, headerSeparator, footerSeparator] { box.boxType = .separator }
        header.font = .systemFont(ofSize: 12, weight: .semibold)
        header.textColor = .secondaryLabelColor
        counter.font = .monospacedDigitSystemFont(ofSize: 11.5, weight: .regular)
        counter.textColor = .tertiaryLabelColor
        preview.font = .monospacedSystemFont(ofSize: 11, weight: .regular)
        preview.textColor = .secondaryLabelColor
        preview.maximumNumberOfLines = 6
        preview.lineBreakMode = .byTruncatingTail
        preview.cell?.truncatesLastVisibleLine = true

        previewImage.imageScaling = .scaleProportionallyDown
        previewImage.imageAlignment = .alignLeft
        previewImage.isHidden = true

        for v in [header, counter, headerSeparator, scroll, separator, preview, previewImage, footerSeparator, hints] as [NSView] {
            v.translatesAutoresizingMaskIntoConstraints = false
            content.addSubview(v)
        }
        let inset = Theme.selectionInset + 10
        previewLeading = preview.leadingAnchor.constraint(equalTo: content.leadingAnchor, constant: inset)
        NSLayoutConstraint.activate([
            header.leadingAnchor.constraint(equalTo: content.leadingAnchor, constant: inset),
            header.centerYAnchor.constraint(equalTo: content.topAnchor, constant: Self.headerHeight / 2),
            counter.trailingAnchor.constraint(equalTo: content.trailingAnchor, constant: -inset),
            counter.centerYAnchor.constraint(equalTo: header.centerYAnchor),
            headerSeparator.topAnchor.constraint(equalTo: content.topAnchor, constant: Self.headerHeight),
            headerSeparator.leadingAnchor.constraint(equalTo: content.leadingAnchor),
            headerSeparator.trailingAnchor.constraint(equalTo: content.trailingAnchor),
            scroll.topAnchor.constraint(equalTo: headerSeparator.bottomAnchor, constant: 6),
            scroll.leadingAnchor.constraint(equalTo: content.leadingAnchor),
            scroll.trailingAnchor.constraint(equalTo: content.trailingAnchor),
            scroll.bottomAnchor.constraint(equalTo: separator.topAnchor, constant: -6),
            separator.leadingAnchor.constraint(equalTo: content.leadingAnchor),
            separator.trailingAnchor.constraint(equalTo: content.trailingAnchor),
            separator.bottomAnchor.constraint(equalTo: footerSeparator.topAnchor, constant: -Self.previewHeight),
            preview.topAnchor.constraint(equalTo: separator.bottomAnchor, constant: 10),
            previewLeading,
            preview.trailingAnchor.constraint(equalTo: content.trailingAnchor, constant: -inset),
            preview.bottomAnchor.constraint(lessThanOrEqualTo: footerSeparator.topAnchor, constant: -8),
            previewImage.topAnchor.constraint(equalTo: separator.bottomAnchor, constant: 10),
            previewImage.leadingAnchor.constraint(equalTo: content.leadingAnchor, constant: inset),
            previewImage.widthAnchor.constraint(equalToConstant: 180),
            previewImage.bottomAnchor.constraint(equalTo: footerSeparator.topAnchor, constant: -10),
            footerSeparator.leadingAnchor.constraint(equalTo: content.leadingAnchor),
            footerSeparator.trailingAnchor.constraint(equalTo: content.trailingAnchor),
            footerSeparator.bottomAnchor.constraint(equalTo: hints.topAnchor),
            hints.leadingAnchor.constraint(equalTo: content.leadingAnchor),
            hints.trailingAnchor.constraint(equalTo: content.trailingAnchor),
            hints.bottomAnchor.constraint(equalTo: content.bottomAnchor),
            hints.heightAnchor.constraint(equalToConstant: Theme.footerHeight),
        ])

        panel.keyDownHandler = { [weak self] event in self?.handleKey(event) ?? false }
    }

    var isVisible: Bool { panel.isVisible }

    /// Called when the panel opens (true) and closes (false). The backwards
    /// hotkey is only claimed in between, so other apps get that key otherwise.
    var onVisibilityChange: ((Bool) -> Void)?

    /// Called for every press of the clipboard hotkey.
    /// `modifiers` are the hotkey's own, watched for release; pass [] to open
    /// the panel in "stay open" mode (from the launcher).
    func hotKeyPressed(reverse: Bool, modifiers: NSEvent.ModifierFlags) {
        if panel.isVisible {
            move(by: reverse ? -1 : 1, wrap: true)
            Log.debug("clipboard: hotkey while open, row \(table.selectedRow)")
            return
        }
        // Backwards only steps through an open list; it never opens one.
        if reverse { return }
        entries = ClipboardStore.shared.entries
        guard !entries.isEmpty else {
            NSSound.beep()
            return
        }
        present(selecting: min(1, entries.count - 1))
        // While the modifier is held, releasing it commits; after a tap, Enter does.
        hints.set(modifiers.isEmpty ? Self.openHints : Self.heldHints(Self.symbols(for: modifiers)))
        panel.makeKeyAndOrderFront(nil)
        shownAt = Date()
        onVisibilityChange?(true)
        Log.debug("clipboard: shown with \(entries.count) entries, row \(table.selectedRow), key=\(panel.isKeyWindow)")
        startWatching(modifiers.subtracting(.shift))
    }

    private static let openHints: [KeyHintBar.Hint] = [
        .init(key: "↩", label: "Copy"), .init(key: "⌫", label: "Delete"), .init(key: "esc", label: "Close"),
    ]

    private static func symbols(for flags: NSEvent.ModifierFlags) -> String {
        var out = ""
        if flags.contains(.control) { out += "⌃" }
        if flags.contains(.option) { out += "⌥" }
        if flags.contains(.command) { out += "⌘" }
        return out
    }

    private static func heldHints(_ modifier: String) -> [KeyHintBar.Hint] {
        [.init(key: "release \(modifier)", label: "Copy"), .init(key: "⌫", label: "Delete"), .init(key: "esc", label: "Cancel")]
    }

    /// Lays the list out for the current `entries` and sizes the panel.
    private func present(selecting row: Int) {
        now = Date()
        previewedID = ""
        table.reloadData()
        // Entry 0 is what is already on the clipboard, so callers start at the one before it.
        select(row)
        let rows = CGFloat(min(entries.count, Self.maxVisibleRows))
        panel.position(height: Self.headerHeight + 1 + rows * Self.rowHeight + 12 + 1 + Self.previewHeight + 1 + Theme.footerHeight)
    }

    /// Renders the panel with made-up entries, for snapshots.
    func debugPresent(_ sample: [ClipboardEntry], selecting row: Int = 1, thumbnail: NSImage? = nil) -> NSPanel {
        entries = sample
        present(selecting: min(row, sample.count - 1))
        if let thumbnail {
            previewImage.image = thumbnail
            previewImage.isHidden = false
            previewLeading.constant = Theme.selectionInset + 10 + 180 + 14
        }
        hints.set(Self.heldHints("⌘"))
        return panel
    }

    private func startWatching(_ modifiers: NSEvent.ModifierFlags) {
        modifierTimer?.invalidate()
        heldModifiers = modifiers
        sawModifiersHeld = false
        guard !modifiers.isEmpty else { return }
        let timer = Timer(timeInterval: 0.03, repeats: true) { [weak self] _ in self?.checkModifiers() }
        RunLoop.main.add(timer, forMode: .common)
        modifierTimer = timer
    }

    private func checkModifiers() {
        let held = NSEvent.modifierFlags.intersection(.deviceIndependentFlagsMask).isSuperset(of: heldModifiers)
        if held {
            sawModifiersHeld = true
        } else if sawModifiersHeld {
            commit()
        } else if Date().timeIntervalSince(shownAt) > 0.25 {
            // The hotkey was tapped and released before we looked: stay open
            // and let Enter / Escape decide.
            Log.debug("clipboard: modifiers never seen held, staying open")
            modifierTimer?.invalidate()
            hints.set(Self.openHints)
        }
    }

    private func select(_ row: Int) {
        guard entries.indices.contains(row) else { return }
        table.selectRowIndexes([row], byExtendingSelection: false)
        table.scrollRowToVisible(row)
        showPreview(of: entries[row])
        counter.stringValue = "\(row + 1) of \(entries.count)"
    }

    /// Text is shown as text. Images and files get a thumbnail, with what is
    /// known about them beside it; the thumbnail arrives when it is ready.
    private func showPreview(of entry: ClipboardEntry) {
        guard entry.id != previewedID else { return }
        previewedID = entry.id
        previewImage.image = nil
        switch entry.kind {
        case .text:
            previewImage.isHidden = true
            previewLeading.constant = Theme.selectionInset + 10
            preview.stringValue = String(entry.text.prefix(2000))
            return
        case .image:
            var lines = [entry.preview, ByteCountFormatter.string(fromByteCount: Int64(entry.payloadBytes), countStyle: .file)]
            if !entry.text.isEmpty { lines.append(String(entry.text.prefix(300))) }
            preview.stringValue = lines.joined(separator: "\n")
        case .files:
            preview.stringValue = entry.files.prefix(6).map(PathDisplay.abbreviate).joined(separator: "\n")
        }
        previewImage.isHidden = false
        previewLeading.constant = Theme.selectionInset + 10 + 180 + 14
        let scale = panel.screen?.backingScaleFactor ?? 2
        ClipboardStore.shared.thumbnail(for: entry, maxPixels: 180 * scale) { [weak self] image in
            guard let self, self.previewedID == entry.id else { return }
            if let image {
                // Thumbnails are sized in pixels; show them at screen scale.
                image.size = NSSize(width: image.size.width / scale, height: image.size.height / scale)
                self.previewImage.image = image
            } else {
                self.previewImage.isHidden = true
                self.previewLeading.constant = Theme.selectionInset + 10
            }
        }
    }

    private func move(by delta: Int, wrap: Bool) {
        guard !entries.isEmpty else { return }
        var next = table.selectedRow + delta
        if wrap {
            next = (next % entries.count + entries.count) % entries.count
        } else {
            next = min(max(next, 0), entries.count - 1)
        }
        select(next)
    }

    private func commit() {
        Log.debug("clipboard: commit row \(table.selectedRow)")
        if entries.indices.contains(table.selectedRow) {
            ClipboardStore.shared.activate(entries[table.selectedRow])
        }
        hide()
    }

    func hide() {
        modifierTimer?.invalidate()
        modifierTimer = nil
        guard panel.isVisible else { return }
        panel.orderOut(nil)
        onVisibilityChange?(false)
    }

    func windowDidResignKey(_ notification: Notification) {
        Log.debug("clipboard: resigned key")
        hide()
    }

    private func handleKey(_ event: NSEvent) -> Bool {
        switch event.keyCode {
        case 125: move(by: 1, wrap: false)       // down
        case 126: move(by: -1, wrap: false)      // up
        case 36, 76: commit()                    // return, enter
        case 53: hide()                          // escape
        case 51, 117:                            // delete
            let row = table.selectedRow
            guard entries.indices.contains(row) else { return true }
            ClipboardStore.shared.remove(entries[row])
            entries.remove(at: row)
            table.reloadData()
            if entries.isEmpty { hide() } else { select(min(row, entries.count - 1)) }
        default: return false
        }
        return true
    }

    @objc private func rowDoubleClicked() {
        if table.clickedRow >= 0 {
            select(table.clickedRow)
            commit()
        }
    }

    func numberOfRows(in tableView: NSTableView) -> Int { entries.count }

    func tableView(_ tableView: NSTableView, viewFor tableColumn: NSTableColumn?, row: Int) -> NSView? {
        let id = NSUserInterfaceItemIdentifier("ClipCell")
        let cell = tableView.makeView(withIdentifier: id, owner: nil) as? ClipboardCell ?? ClipboardCell(identifier: id)
        cell.label.stringValue = entries[row].preview
        cell.setKind(entries[row].kind)
        cell.age.stringValue = row == 0 ? "current" : Self.age(of: entries[row].date, now: now)
        return cell
    }

    func tableView(_ tableView: NSTableView, rowViewForRow row: Int) -> NSTableRowView? {
        ResultRowView()
    }

    func tableViewSelectionDidChange(_ notification: Notification) {
        if entries.indices.contains(table.selectedRow) {
            showPreview(of: entries[table.selectedRow])
            counter.stringValue = "\(table.selectedRow + 1) of \(entries.count)"
        }
    }

    private static func age(of date: Date, now: Date) -> String {
        let seconds = max(0, Int(now.timeIntervalSince(date)))
        switch seconds {
        case ..<60: return "now"
        case ..<3600: return "\(seconds / 60)m"
        case ..<86400: return "\(seconds / 3600)h"
        default: return "\(seconds / 86400)d"
        }
    }
}

final class ClipboardCell: NSTableCellView {
    let label = NSTextField(labelWithString: "")
    let age = NSTextField(labelWithString: "")
    private let icon = NSImageView()
    private static let symbols: [ClipboardEntry.Kind: NSImage] = {
        let config = NSImage.SymbolConfiguration(pointSize: 12, weight: .medium)
        let names: [ClipboardEntry.Kind: String] = [.text: "text.alignleft", .image: "photo", .files: "doc.on.doc"]
        return names.compactMapValues { NSImage(systemSymbolName: $0, accessibilityDescription: nil)?.withSymbolConfiguration(config) }
    }()

    init(identifier: NSUserInterfaceItemIdentifier) {
        super.init(frame: .zero)
        self.identifier = identifier
        label.font = .systemFont(ofSize: 13)
        label.lineBreakMode = .byTruncatingTail
        label.setContentCompressionResistancePriority(.defaultLow, for: .horizontal)
        age.font = .monospacedDigitSystemFont(ofSize: 11.5, weight: .regular)
        age.alignment = .right
        age.setContentHuggingPriority(.required, for: .horizontal)
        age.setContentCompressionResistancePriority(.required, for: .horizontal)
        icon.imageScaling = .scaleNone
        for v in [icon, label, age] as [NSView] {
            v.translatesAutoresizingMaskIntoConstraints = false
            addSubview(v)
        }
        let inset = Theme.selectionInset + 10
        NSLayoutConstraint.activate([
            icon.leadingAnchor.constraint(equalTo: leadingAnchor, constant: inset),
            icon.centerYAnchor.constraint(equalTo: centerYAnchor),
            icon.widthAnchor.constraint(equalToConstant: 18),
            label.leadingAnchor.constraint(equalTo: icon.trailingAnchor, constant: 8),
            label.trailingAnchor.constraint(lessThanOrEqualTo: age.leadingAnchor, constant: -12),
            label.centerYAnchor.constraint(equalTo: centerYAnchor),
            age.trailingAnchor.constraint(equalTo: trailingAnchor, constant: -inset),
            age.centerYAnchor.constraint(equalTo: centerYAnchor),
        ])
    }

    required init?(coder: NSCoder) { fatalError("not used") }

    func setKind(_ kind: ClipboardEntry.Kind) {
        icon.image = Self.symbols[kind]
    }

    override var backgroundStyle: NSView.BackgroundStyle {
        didSet {
            let selected = backgroundStyle == .emphasized
            label.textColor = selected ? .white : .labelColor
            age.textColor = selected ? NSColor.white.withAlphaComponent(0.75) : .tertiaryLabelColor
            icon.contentTintColor = selected ? .white : .secondaryLabelColor
        }
    }
}
